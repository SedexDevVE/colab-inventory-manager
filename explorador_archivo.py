        "# ----------------------------- Ordenamiento ---------------------------\n",
        "def _va_antes(a, b, descendente):\n",
        "    return a >= b if descendente else a <= b\n",
        "\n",
        "def insertion_sort(lista, clave, descendente=False, stats=None):\n",
        "    stats = stats if stats is not None else {'comparaciones': 0}\n",
        "    res = list(lista)\n",
        "    for i in range(1, len(res)):\n",
        "        actual = res[i]\n",
        "        k = clave(actual)\n",
        "        j = i - 1\n",
        "        while j >= 0:\n",
        "            stats['comparaciones'] += 1\n",
        "            if _va_antes(clave(res[j]), k, descendente):\n",
        "                break\n",
        "            res[j + 1] = res[j]\n",
        "            j -= 1\n",
        "        res[j + 1] = actual\n",
        "    return res\n",
        "\n",
        "def merge_sort(lista, clave, descendente=False, stats=None):\n",
        "    stats = stats if stats is not None else {'comparaciones': 0}\n",
        "    if len(lista) <= 1:\n",
        "        return list(lista)\n",
        "    medio = len(lista) // 2\n",
        "    izq = merge_sort(lista[:medio], clave, descendente, stats)\n",
        "    der = merge_sort(lista[medio:], clave, descendente, stats)\n",
        "    res, i, j = [], 0, 0\n",
        "    while i < len(izq) and j < len(der):\n",
        "        stats['comparaciones'] += 1\n",
        "        if _va_antes(clave(izq[i]), clave(der[j]), descendente):\n",
        "            res.append(izq[i]); i += 1\n",
        "        else:\n",
        "            res.append(der[j]); j += 1\n",
        "    res.extend(izq[i:])\n",
        "    res.extend(der[j:])\n",
        "    return res\n",
        "\n",
        "def ordenar(lista, clave, descendente=False):\n",
        "    stats = {'comparaciones': 0}\n",
